import { FeatureContribution, PredictionResult } from '../../types/ml';
import { diabetesFeatures } from './schema';

/**
 * EDUCATIONAL DEMONSTRATION SIMULATOR ONLY.
 * Transparent illustrative scoring formula showing how metabolic inputs
 * shift a logistic risk curve. NOT a trained clinical model.
 */
export function runDiabetesDemoPrediction(inputs: Record<string, number>): PredictionResult {
  const pregnancies = inputs.pregnancies ?? 2;
  const glucose = inputs.glucose ?? 112;
  const bloodPressure = inputs.bloodPressure ?? 72;
  const skinThickness = inputs.skinThickness ?? 23;
  const insulin = inputs.insulin ?? 88;
  const bmi = inputs.bmi ?? 27.4;
  const dpf = inputs.dpf ?? 0.42;
  const age = inputs.age ?? 34;

  const rawEffects: Record<string, number> = {
    pregnancies: ((pregnancies - 3.5) / 5) * 0.34,
    glucose: ((glucose - 122) / 35) * 1.15,
    bloodPressure: ((bloodPressure - 72) / 20) * 0.14,
    skinThickness: ((skinThickness - 22) / 18) * 0.12,
    insulin: ((insulin - 110) / 150) * 0.22,
    bmi: ((bmi - 30) / 8) * 0.72,
    dpf: ((dpf - 0.5) / 0.5) * 0.44,
    age: ((age - 35) / 14) * 0.36,
  };

  const logit = Object.values(rawEffects).reduce((acc, v) => acc + v, -0.35);
  const probability = 1 / (1 + Math.exp(-logit));
  const clampedProb = Math.min(0.96, Math.max(0.04, probability));
  const predictedClass: 0 | 1 = clampedProb >= 0.5 ? 1 : 0;

  const riskTier =
    clampedProb < 0.35
      ? 'Low Demonstration Index'
      : clampedProb < 0.65
      ? 'Moderate Demonstration Index'
      : 'Elevated Demonstration Index';

  const contributions: FeatureContribution[] = diabetesFeatures
    .map((f) => {
      const impact = rawEffects[f.key] ?? 0;
      const direction: FeatureContribution['direction'] =
        impact > 0.05 ? 'elevating' : impact < -0.05 ? 'reducing' : 'neutral';
      return {
        key: f.key,
        label: f.shortLabel,
        value: inputs[f.key] ?? f.defaultValue,
        unit: f.unit,
        impact: Number(impact.toFixed(3)),
        direction,
      };
    })
    .sort((a, b) => Math.abs(b.impact) - Math.abs(a.impact));

  return {
    diseaseId: 'diabetes',
    source: 'educational_demo_simulator',
    isTrainedModel: false,
    predictedClass,
    predictedLabel:
      predictedClass === 1
        ? 'Demo Class 1: Elevated Risk Simulation'
        : 'Demo Class 0: Lower Risk Simulation',
    probability: Number(clampedProb.toFixed(4)),
    riskTier,
    summaryNote:
      'Generated by an educational demonstration scoring formula for classroom visualization. Connect a trained Python Scikit-learn model for empirical predictions.',
    contributions,
    timestampIso: new Date().toISOString(),
  };
}
