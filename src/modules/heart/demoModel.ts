import { FeatureContribution, PredictionResult } from '../../types/ml';
import { heartFeatures } from './schema';

/**
 * EDUCATIONAL DEMONSTRATION SIMULATOR ONLY.
 * This function applies transparent, illustrative linear weights to normalized
 * input features so students can observe how a binary classifier responds to
 * feature changes. It is NOT a trained Scikit-learn model and NOT medical advice.
 */
export function runHeartDemoPrediction(inputs: Record<string, number>): PredictionResult {
  const age = inputs.age ?? 52;
  const sex = inputs.sex ?? 1;
  const cp = inputs.cp ?? 1;
  const trestbps = inputs.trestbps ?? 126;
  const chol = inputs.chol ?? 224;
  const fbs = inputs.fbs ?? 0;
  const thalach = inputs.thalach ?? 156;
  const exang = inputs.exang ?? 0;
  const oldpeak = inputs.oldpeak ?? 0.8;
  const slope = inputs.slope ?? 2;
  const ca = inputs.ca ?? 0;
  const thal = inputs.thal ?? 2;

  const rawEffects: Record<string, number> = {
    age: ((age - 54) / 15) * 0.42,
    sex: sex === 1 ? 0.18 : -0.14,
    cp: cp === 3 ? 0.52 : cp === 0 ? 0.18 : -0.25,
    trestbps: ((trestbps - 130) / 30) * 0.28,
    chol: ((chol - 240) / 80) * 0.22,
    fbs: fbs === 1 ? 0.14 : -0.05,
    restecg: (inputs.restecg ?? 1) === 2 ? 0.18 : 0,
    thalach: ((150 - thalach) / 35) * 0.48,
    exang: exang === 1 ? 0.56 : -0.18,
    oldpeak: ((oldpeak - 1.0) / 1.8) * 0.54,
    slope: slope === 0 ? 0.34 : slope === 1 ? 0.16 : -0.24,
    ca: (ca - 0.5) * 0.42,
    thal: thal === 3 ? 0.48 : thal === 1 ? 0.24 : -0.26,
  };

  const logit = Object.values(rawEffects).reduce((acc, v) => acc + v, -0.15);
  const probability = 1 / (1 + Math.exp(-logit));
  const clampedProb = Math.min(0.96, Math.max(0.04, probability));
  const predictedClass: 0 | 1 = clampedProb >= 0.5 ? 1 : 0;

  const riskTier =
    clampedProb < 0.35
      ? 'Low Demonstration Index'
      : clampedProb < 0.65
      ? 'Moderate Demonstration Index'
      : 'Elevated Demonstration Index';

  const contributions: FeatureContribution[] = heartFeatures
    .map((f) => {
      const impact = rawEffects[f.key] ?? 0;
      const direction: FeatureContribution['direction'] =
        impact > 0.05 ? 'elevating' : impact < -0.05 ? 'reducing' : 'neutral';
      return {
        key: f.key,
        label: f.shortLabel,
        value: inputs[f.key] ?? f.defaultValue,
        unit: f.unit,
        impact: Number(impact.toFixed(3)),
        direction,
      };
    })
    .sort((a, b) => Math.abs(b.impact) - Math.abs(a.impact))
    .slice(0, 7);

  return {
    diseaseId: 'heart',
    source: 'educational_demo_simulator',
    isTrainedModel: false,
    predictedClass,
    predictedLabel:
      predictedClass === 1
        ? 'Demo Class 1: Elevated Risk Simulation'
        : 'Demo Class 0: Lower Risk Simulation',
    probability: Number(clampedProb.toFixed(4)),
    riskTier,
    summaryNote:
      'Generated by an educational demonstration scoring formula for classroom visualization. Connect a trained Python Scikit-learn model for empirical predictions.',
    contributions,
    timestampIso: new Date().toISOString(),
  };
}
