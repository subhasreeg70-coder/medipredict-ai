import { FeatureContribution, PredictionResult } from '../../types/ml';
import { breastCancerFeatures } from './schema';

/**
 * EDUCATIONAL DEMONSTRATION SIMULATOR ONLY.
 * Transparent illustrative scoring formula demonstrating morphological feature
 * sensitivity on WDBC mean measurements. NOT a trained clinical classifier.
 */
export function runBreastCancerDemoPrediction(inputs: Record<string, number>): PredictionResult {
  const meanRadius = inputs.meanRadius ?? 13.2;
  const meanTexture = inputs.meanTexture ?? 18.4;
  const meanPerimeter = inputs.meanPerimeter ?? 85.0;
  const meanArea = inputs.meanArea ?? 540;
  const meanSmoothness = inputs.meanSmoothness ?? 0.094;
  const meanCompactness = inputs.meanCompactness ?? 0.088;
  const meanConcavity = inputs.meanConcavity ?? 0.062;
  const meanConcavePoints = inputs.meanConcavePoints ?? 0.036;
  const meanSymmetry = inputs.meanSymmetry ?? 0.176;
  const meanFractalDimension = inputs.meanFractalDimension ?? 0.062;

  const rawEffects: Record<string, number> = {
    meanRadius: ((meanRadius - 14.5) / 3.5) * 0.85,
    meanTexture: ((meanTexture - 19.5) / 4.5) * 0.42,
    meanPerimeter: ((meanPerimeter - 94) / 24) * 0.82,
    meanArea: ((meanArea - 675) / 350) * 0.78,
    meanSmoothness: ((meanSmoothness - 0.098) / 0.015) * 0.28,
    meanCompactness: ((meanCompactness - 0.11) / 0.05) * 0.46,
    meanConcavity: ((meanConcavity - 0.095) / 0.075) * 0.72,
    meanConcavePoints: ((meanConcavePoints - 0.052) / 0.038) * 0.92,
    meanSymmetry: ((meanSymmetry - 0.183) / 0.028) * 0.22,
    meanFractalDimension: ((meanFractalDimension - 0.063) / 0.008) * 0.08,
  };

  const logit = Object.values(rawEffects).reduce((acc, v) => acc + v, -0.2);
  const probability = 1 / (1 + Math.exp(-logit));
  const clampedProb = Math.min(0.97, Math.max(0.03, probability));
  const predictedClass: 0 | 1 = clampedProb >= 0.5 ? 1 : 0;

  const riskTier =
    clampedProb < 0.35
      ? 'Low Demonstration Index'
      : clampedProb < 0.65
      ? 'Moderate Demonstration Index'
      : 'Elevated Demonstration Index';

  const contributions: FeatureContribution[] = breastCancerFeatures
    .map((f) => {
      const impact = rawEffects[f.key] ?? 0;
      const direction: FeatureContribution['direction'] =
        impact > 0.05 ? 'elevating' : impact < -0.05 ? 'reducing' : 'neutral';
      return {
        key: f.key,
        label: f.shortLabel,
        value: inputs[f.key] ?? f.defaultValue,
        unit: f.unit,
        impact: Number(impact.toFixed(3)),
        direction,
      };
    })
    .sort((a, b) => Math.abs(b.impact) - Math.abs(a.impact))
    .slice(0, 7);

  return {
    diseaseId: 'breast-cancer',
    source: 'educational_demo_simulator',
    isTrainedModel: false,
    predictedClass,
    predictedLabel:
      predictedClass === 1
        ? 'Demo Class 1: Malignant-Pattern Simulation'
        : 'Demo Class 0: Benign-Pattern Simulation',
    probability: Number(clampedProb.toFixed(4)),
    riskTier,
    summaryNote:
      'Generated by an educational demonstration scoring formula for classroom visualization. Connect a trained Python Scikit-learn model for empirical predictions.',
    contributions,
    timestampIso: new Date().toISOString(),
  };
}
